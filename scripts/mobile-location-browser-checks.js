async (page) => {
  // Native browser geolocation is emulated here; this does not establish device GPS accuracy.
  const check = (value, message) => { if (!value) throw new Error(message); };
  const base = page.url().startsWith('http://127.0.0.1:8000') ? 'http://127.0.0.1:8000' : 'http://127.0.0.1:5173';
  const errors = [];
  const capturedPlan = null; // May be replaced in an ignored copy with a verified replay fixture.
  page.on('pageerror', error => errors.push(error.message));
  await page.unroute('**/api/plan');
  await page.clock.setSystemTime(new Date());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(base);
  await page.evaluate(() => localStorage.removeItem('spotter-appearance'));
  await page.reload();
  check(await page.locator('.gps-marker').count() === 0, 'Location must start off');
  await page.route('**/api/plan', async request => {
    await new Promise(resolve => setTimeout(resolve, 4500));
    if (capturedPlan) await request.fulfill({ status: 200, json: capturedPlan });
    else await request.continue();
  });
  const response = page.waitForResponse(response => response.url().endsWith('/api/plan') && response.status() === 200, { timeout: 95000 });
  await page.getByRole('button', { name: 'Compare routes', exact: true }).click();
  await page.getByRole('progressbar', { name: 'Checking routes and forecasts' }).waitFor();
  const rotation = await page.locator('.spinner').evaluate(el => getComputedStyle(el).transform);
  await page.waitForFunction(previous => getComputedStyle(document.querySelector('.spinner')).transform !== previous, rotation);
  await page.getByText(/2s elapsed/).waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check(await page.locator('.spinner').evaluate(el => getComputedStyle(el).animationName === 'none'), 'Reduced motion must be respected');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await response;
  await page.getByRole('button', { name: 'Show routes', exact: true }).waitFor();
  await page.unroute('**/api/plan');
  for (const size of [{ width: 390, height: 844 }, { width: 320, height: 667 }, { width: 390, height: 700 }]) {
    await page.setViewportSize(size);
    await page.getByRole('button', { name: 'Show routes', exact: true }).click();
    const panel = await page.locator('.sidebar-body').boundingBox();
    const map = await page.locator('.map').boundingBox();
    check(panel.height <= size.height * 0.37, 'Result panel must leave room for the map');
    check(map.y + map.height <= panel.y + 1, 'Bottom sheet must not cover the map');
    const dock = await page.locator('.mobile-planning-actions').boundingBox();
    check(dock.y + dock.height <= size.height + 1 && dock.y >= size.height - 100, 'Dock must stay inside the visible viewport bottom');
    check(panel.y + panel.height <= dock.y + 1, 'Sheet must end above the bottom dock');
    await page.getByRole('button', { name: /^2 Route 2/ }).click();
    check(!await page.locator('.sidebar-body').isVisible(), 'Selecting a route must close the mobile panel');
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Show routes');
    await page.getByRole('button', { name: 'Show weather', exact: true }).click();
    check(await page.getByRole('checkbox', { name: 'Weather layer', exact: true }).isVisible(), 'Weather layer toggle must stay accessible');
    await page.getByRole('slider', { name: 'Forecast hour after departure' }).focus();
    await page.keyboard.press('End');
    check(await page.getByRole('slider', { name: 'Forecast hour after departure' }).inputValue() === '48', 'Mobile weather slider remains usable');
    await page.getByRole('button', { name: 'Close planning panel', exact: true }).click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight), 'Mobile viewport must not overflow');
  }
  await page.setViewportSize({ width: 390, height: 844 });
  const safeArea = await page.context().newCDPSession(page);
  await safeArea.send('Emulation.setSafeAreaInsetsOverride', { insets: { bottom: 34, top: 0, left: 0, right: 0 } });
  await page.waitForFunction(() => document.querySelector('.mobile-planning-actions').getBoundingClientRect().height >= 97);
  check(await page.locator('.mobile-planning-actions').evaluate(el => [...el.querySelectorAll('button')].every(button => button.getBoundingClientRect().bottom <= innerHeight - 34)), 'Dock actions must clear the emulated gesture safe area');
  await page.screenshot({ path: 'output/playwright/bottom-dock-safe-area.png' });
  await safeArea.send('Emulation.setSafeAreaInsetsOverride', { insets: { bottom: 0, top: 0, left: 0, right: 0 } });
  await safeArea.detach();
  await page.getByRole('button', { name: 'Map settings', exact: true }).click();
  await page.getByLabel('Appearance', { exact: true }).selectOption('dark');
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.addScriptTag({ url: 'http://127.0.0.1:5173/node_modules/axe-core/axe.min.js' });
  const scan = () => page.evaluate(async () => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }));
  let axe = await scan();
  check(axe.violations.length === 0, JSON.stringify(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))));
  await page.getByRole('button', { name: 'Close map settings', exact: true }).click();
  await page.getByRole('button', { name: 'Show routes', exact: true }).click();
  axe = await scan();
  check(axe.violations.length === 0, JSON.stringify(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))));
  await page.screenshot({ path: 'output/playwright/mobile-night-routes.png' });
  await page.getByRole('button', { name: 'Close planning panel', exact: true }).click();
  await page.reload();
  check(await page.locator('html').getAttribute('data-theme') === 'dark', 'Appearance must survive refresh');
  await page.getByRole('button', { name: 'Trip details', exact: true }).click();
  await page.getByRole('button', { name: 'Map settings', exact: true }).click();
  await page.getByLabel('Appearance', { exact: true }).selectOption('auto');
  const night = new Date(2026, 9, 13, 20, 0);
  await page.clock.setFixedTime(night);
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.clock.setFixedTime(new Date(2026, 9, 14, 6, 0));
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.clock.setSystemTime(new Date());
  await page.getByLabel('Appearance', { exact: true }).selectOption('light');
  await page.getByRole('button', { name: 'Close map settings', exact: true }).click();
  const cdp = await page.context().newCDPSession(page);
  const { targetInfo } = await cdp.send('Target.getTargetInfo');
  const browserContextId = targetInfo.browserContextId;
  await cdp.send('Browser.setPermission', { permission: { name: 'geolocation' }, setting: 'denied', origin: base, browserContextId });
  await page.getByRole('button', { name: 'Enable device location', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Location permission denied.' }).waitFor();
  check(await page.locator('.gps-marker').count() === 0, 'Denied location must not create a marker');
  await cdp.send('Browser.setPermission', { permission: { name: 'geolocation' }, setting: 'granted', origin: base, browserContextId });
  await page.context().setGeolocation({ longitude: -87.63, latitude: 41.88, accuracy: 25 });
  let requests = 0;
  const count = request => { if (request.url().includes('/api/')) requests++; };
  page.on('request', count);
  await page.getByRole('button', { name: 'Enable device location', exact: true }).click();
  await page.locator('.gps-marker').waitFor();
  await page.locator('.location-status').filter({ hasText: 'Device location · ±25 m' }).waitFor();
  await page.context().setGeolocation({ longitude: -87.62, latitude: 41.89, accuracy: 40 });
  await page.waitForFunction(() => document.querySelector('.gps-marker').dataset.coordinate === '-87.62,41.89');
  await page.context().setOffline(true);
  await page.locator('.location-status').filter({ hasText: 'Location paused · browser offline' }).waitFor();
  check(await page.locator('.gps-marker.gps-stale').count() === 1, 'Offline fix must be styled as old');
  await page.context().setOffline(false);
  await page.locator('.location-status').filter({ hasText: 'Device location · ±40 m' }).waitFor();
  await page.clock.setFixedTime(new Date(Date.now() + 120000));
  await page.waitForFunction(() => document.querySelector('.location-status').textContent.includes('over 1 minute old'), null, { timeout: 15000 });
  check(await page.locator('.gps-marker.gps-stale').count() === 1, 'Old fixes must not look current');
  await page.clock.setSystemTime(new Date());
  await page.screenshot({ path: 'output/playwright/mobile-gps-emulated.png' });
  await page.getByRole('button', { name: 'Stop device location', exact: true }).click();
  check(await page.locator('.gps-marker').count() === 0, 'Stop must remove location');
  await page.context().setGeolocation({ longitude: -87.6, latitude: 41.9 });
  check(await page.locator('.gps-marker').count() === 0, 'Stopped watch must remain stopped');
  check(requests === 0, `Location must not call the planner API: ${requests}`);
  page.off('request', count);
  await cdp.send('Browser.resetPermissions', { browserContextId });
  await cdp.detach();
  await page.setViewportSize({ width: 1365, height: 679 });
  await page.reload();
  check(errors.length === 0, `JavaScript errors: ${errors.join('; ')}`);
  return { passed: true, base, providerData: capturedPlan ? 'captured provider replay, not a fresh forecast' : 'live API response', gps: 'emulated native browser position, denial, movement, offline/resume, stale, stop', locationAPICalls: requests, mobileSizes: ['390×844','320×667','390×700'], safeAreaInset: 34, darkAxeViolations: 0, javascriptErrors: errors };
}
